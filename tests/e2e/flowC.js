const { setup, shot, api, staffToken, mobLogin, WEB, MOB } = require('./common');
(async () => {
  const { b, web, mob, errs } = await setup();
  process.on('exit', () => console.log('ERRS', errs.slice(0, 8)));
  const t = await staffToken();
  await api('/demo/reset', 'POST', {}, t);
  await new Promise(r => setTimeout(r, 1500));
  await mobLogin(mob, 'priya@demo.test');
  await shot(mob, 'C0-priya-home');
  await web.goto(WEB + '/demo'); await web.waitForTimeout(2500);
  await web.getByRole('button', { name: /Simulate forecast high/i }).click();
  await web.waitForTimeout(1500);
  await web.goto(WEB + '/feeders'); await web.waitForTimeout(2500);
  await web.getByRole('link', { name: /Send stop-charging request/ }).or(web.getByRole('button', { name: /Send stop-charging request/ })).first().click();
  await web.waitForTimeout(2500);
  await shot(web, 'C1-campaign-stop', true);
  await web.getByRole('button', { name: /^Send to \d+ customers/ }).click();
  await mob.waitForTimeout(2500);
  await shot(mob, 'C2-mob-banner');
  await mob.goto(MOB + '/messages'); await mob.waitForTimeout(2500);
  await mob.getByText(/Please pause EV charging/).first().click(); await mob.waitForTimeout(2500);
  await shot(mob, 'C3-stop-alert');
  await mob.getByText(/Yes, I.ll pause/).click(); await mob.waitForTimeout(400);
  await mob.getByText('Confirm', { exact: true }).click(); await mob.waitForTimeout(2000);
  await shot(mob, 'C4-responded');
  await web.waitForTimeout(8000);
  await web.getByRole('button', { name: /Start event now/ }).click(); await web.waitForTimeout(6000);
  await mob.goto(MOB + '/'); await mob.waitForTimeout(6000);
  await shot(mob, 'C5-home-during-event');
  await web.getByRole('button', { name: /End event now/ }).click(); await web.waitForTimeout(4000);
  await shot(mob, 'C6-mob-after-end');
  await shot(web, 'C7-campaign-results', true);
  const banner = mob.getByText(/event result/i).first();
  if (await banner.count()) { await banner.click(); } else { const cs = await api('/campaigns', 'GET', null, t); await mob.goto(MOB + '/dr-events/' + cs[0].drEventId + '/result'); }
  await mob.waitForTimeout(3000);
  await shot(mob, 'C8-result');
  const cs = await api('/campaigns', 'GET', null, t);
  console.log('DR stats', JSON.stringify(cs[0].stats));
  await b.close();
})().catch(e => { console.error('FAIL', e.message.slice(0, 400)); process.exit(1); });
