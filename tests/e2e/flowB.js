const { setup, shot, api, staffToken, mobLogin, WEB, MOB } = require('./common');
(async () => {
  const { b, web, mob, errs } = await setup();
  process.on('exit', () => console.log('ERRS', errs.slice(0, 8)));
  const t = await staffToken();
  await api('/demo/reset', 'POST', {}, t);
  await new Promise(r => setTimeout(r, 1500));
  await mobLogin(mob, 'manny@demo.test');
  await web.goto(WEB + '/demo'); await web.waitForTimeout(2500);
  await web.getByRole('button', { name: /Simulate 284 EVs stopped charging/i }).click();
  await web.waitForTimeout(1500);
  await web.goto(WEB + '/feeders'); await web.waitForTimeout(2500);
  await shot(web, 'B1-feeders-event');
  await web.getByRole('link', { name: /Target 118/ }).or(web.getByRole('button', { name: /Target 118/ })).first().click();
  await web.waitForTimeout(2500);
  await shot(web, 'B2-campaign', true);
  console.log('CAMPAIGN audience text:', (await web.innerText('main')).match(/.{0,60}customers.{0,40}/g)?.slice(0, 4));
  await web.getByRole('button', { name: /^Send to \d+ customers/ }).click();
  await mob.waitForTimeout(2500);
  await shot(mob, 'B3-mob-banner');
  console.log('MOB banner text:', (await mob.innerText('body')).slice(0, 250));
  await web.waitForTimeout(12000);
  await shot(web, 'B4-campaign-sent', true);
  await mob.goto(MOB + '/messages'); await mob.waitForTimeout(2500);
  await shot(mob, 'B5-inbox');
  await mob.getByText(/saving with/).first().click(); await mob.waitForTimeout(2500);
  await shot(mob, 'B6-offer');
  await mob.getByText(/Enroll in 1 minute/).click(); await mob.waitForTimeout(2000);
  await mob.getByRole('checkbox').first().click(); await mob.waitForTimeout(400);
  await mob.getByText('Enroll now').click(); await mob.waitForTimeout(3000);
  await shot(mob, 'B7-enrolled');
  await web.waitForTimeout(15000);
  await shot(web, 'B8-campaign-final', true);
  const cs = await api('/campaigns', 'GET', null, t);
  console.log('CAMPAIGN stats', JSON.stringify(cs[0].stats), 'demoMsg', cs[0].demoMessageId);
  const ov = await api('/stats/overview', 'GET', null, t);
  console.log('OVERVIEW', ov.knownEvs, ov.unenrolledEvs, ov.invisiblePct);
  await b.close();
})().catch(e => { console.error('FAIL', e.message.slice(0, 400)); process.exit(1); });
